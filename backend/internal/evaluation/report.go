type reportCriterion struct {
	Title         string
	Weight        int
	Score         int
	AIScore       int
	Overridden    bool
	Justification string
}

type reportData struct {
	Lang          string
	L             map[string]string
	Color         string
	University    string
	Title         string
	Total         int
	Level         string
	PreviousTotal *int
	Delta         string
	Criteria      []reportCriterion
	RedFlags      []apigen.RedFlag
	Hypotheses    []string
	Experiments   []apigen.Experiment
	Recommends    []string
	Summary       string
	Disclaimer    string
}

func valueOr(p *string, fallback string) string {
	if p == nil || *p == "" {
		return fallback
	}
	return *p
}

// Report renders the evaluation as a PDF.
func (s *Service) Report(ctx context.Context, projectID, evaluationID uuid.UUID, lang string) ([]byte, string, error) {
	a, err := s.Projects.Access(ctx, projectID)
	if err != nil {
		return nil, "", err
	}
	row, err := s.load(ctx, projectID, evaluationID)
	if err != nil {
		return nil, "", err
	}
	if row.Status != StatusReady {
		return nil, "", errNotReady
	}
	e, err := s.view(ctx, a, &row)
	if err != nil {
		return nil, "", err
	}
	if lang == "" {
		lang = string(e.Locale)
	}
	l := reportLabels[lang]
	if l == nil {
		lang, l = "ru", reportLabels["ru"]
	}
	settings, err := s.Tenants.CurrentSettings(ctx)
	if err != nil {
		return nil, "", err
	}
	d := reportData{
		Lang: lang, L: l, Color: "#" + brandColor(settings.PrimaryColor), University: settings.ShortName.Best(lang),
		Title: a.Project.Title, Total: *e.Total, PreviousTotal: e.PreviousTotal, RedFlags: e.RedFlags, Hypotheses: e.Hypotheses,
		Experiments: e.Experiments, Recommends: e.Recommendations, Summary: e.Summary,
	}
	if e.Level != nil {
		d.Level = LevelNames[string(*e.Level)][lang]
	}
	if e.PreviousTotal != nil {
		diff := *e.Total - *e.PreviousTotal
		d.Delta = strconv.Itoa(diff)
		if diff > 0 {
			d.Delta = "+" + d.Delta
		}
	}
	titles := map[string]string{}
	for _, c := range DefaultRubric {
		titles[c.Key] = c.Title.Best(lang)
	}
	for _, c := range e.Criteria {
		d.Criteria = append(d.Criteria, reportCriterion{
			Title: titles[c.Key], Weight: c.Weight, Score: c.Score, AIScore: c.AiScore,
			Overridden: c.Overridden, Justification: c.Justification,
		})
	}
	when := row.CreatedAt
	if row.CompletedAt != nil {
		when = *row.CompletedAt
	}
	d.Disclaimer = fmt.Sprintf(l["disclaimer"], valueOr(e.Model, "—"), valueOr(e.PromptVersion, "—"), when.Format("02.01.2006"))
	var buf bytes.Buffer
	if err := reportTemplate.ExecuteTemplate(&buf, "report.html", d); err != nil {
		return nil, "", fmt.Errorf("evaluation: report: %w", err)
	}
	pdf, err := s.Gotenberg.HTMLToPDF(ctx, buf.Bytes(), gotenberg.Page{PreferCSSPageSize: true})
	if err != nil {
		return nil, "", asConverterError(err)
	}
	return pdf, fmt.Sprintf("%s-evaluation-%s.pdf", fileSlug(a.Project.Title), when.Format(time.DateOnly)), nil
}

var hexColor = regexp.MustCompile(`^#?([0-9a-fA-F]{6})$`)

func brandColor(c string) string {
	if m := hexColor.FindStringSubmatch(c); m != nil {
		return strings.ToUpper(m[1])
	}
	return "00A3C4"
}

var slugUnsafe = regexp.MustCompile(`[^\p{L}\p{N}]+`)

func fileSlug(title string) string {
	s := strings.Trim(slugUnsafe.ReplaceAllString(strings.ToLower(title), "-"), "-")
	if r := []rune(s); len(r) > 60 {
		s = string(r[:60])
	}
	if s == "" {
		return "project"
	}
	return s
}

// pdfResponse sends a PDF as an attachment.
type pdfResponse struct {
	name string
	data []byte
}

func (p pdfResponse) VisitGetEvaluationReportResponse(w http.ResponseWriter) error {
	h := w.Header()
	h.Set("Content-Type", "application/pdf")
	h.Set("Content-Length", strconv.Itoa(len(p.data)))
	h.Set("Content-Disposition", mime.FormatMediaType("attachment", map[string]string{"filename": p.name}))
	h.Set("Cache-Control", "private, no-store")
	w.WriteHeader(http.StatusOK)
	_, err := w.Write(p.data)
	return err
}
