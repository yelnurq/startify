func formatDate(t time.Time, locale string) string {
	m := months[locale][t.Month()-1]
	switch locale {
	case "en":
		return fmt.Sprintf("%d %s %d", t.Day(), m, t.Year())
	case "kk":
		return fmt.Sprintf("%d жылғы %d %s", t.Year(), t.Day(), m)
	}
	return fmt.Sprintf("%d %s %d", t.Day(), m, t.Year())
}

// docData feeds the document templates.
type docData struct {
	Lang      string
	L         map[string]string
	Title     string
	Tagline   string
	Industry  string
	Brand     Brand
	Color     string
	Content   PitchContent
	Sections  []section
	Slides    []Slide
	Generated string
	// Passport only.
	Progress string
	Percent  int
	Team     []string
	Contact  string
	URL      string
	QR       template.HTML
}

type section struct {
	Title string
	Text  string
}

func newDocData(card ProjectCard, c PitchContent, brand Brand, locale string, now time.Time) docData {
	l := labels[locale]
	if l == nil {
		locale, l = "ru", labels["ru"]
	}
	d := docData{
		Lang: locale, L: l, Title: card.Title, Tagline: firstNonEmpty(c.Tagline, card.Tagline), Industry: industryName(card.Industry, locale),
		Brand: brand, Color: "#" + brand.hexColor(), Content: c, Slides: c.Slides,
		Generated: fmt.Sprintf(l["generated"], formatDate(now, locale)),
	}
	for _, s := range []section{
		{l["problem"], c.Problem},
		{l["customer"], c.Customer},
		{l["solution"], c.Solution},
		{l["market"], c.Market},
		{l["competition"], c.Competition},
		{l["business_model"], c.Business},
		{l["traction"], c.Traction},
		{l["team"], c.Team},
		{l["ask"], c.Ask},
	} {
		if strings.TrimSpace(s.Text) != "" {
			d.Sections = append(d.Sections, s)
		}
	}
	return d
}

func render(name string, d docData) ([]byte, error) {
	var buf bytes.Buffer
	if err := documents.ExecuteTemplate(&buf, name, d); err != nil {
		return nil, fmt.Errorf("incubator: render %s: %w", name, err)
	}
	return buf.Bytes(), nil
}

// qrSVG draws a QR code of the text as an inline SVG.
func qrSVG(text string) (template.HTML, error) {
	code, err := qr.Encode(text, qr.M)
	if err != nil {
		return "", fmt.Errorf("incubator: qr: %w", err)
	}
	const quiet = 4
	size := code.Size + 2*quiet
	var b strings.Builder
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" shape-rendering="crispEdges" role="img">`, size, size)
	fmt.Fprintf(&b, `<rect width="%d" height="%d" fill="#fff"/><path fill="#101828" d="`, size, size)
	for y := range code.Size {
		for x := range code.Size {
			if code.Black(x, y) {
				fmt.Fprintf(&b, "M%d %dh1v1h-1z", x+quiet, y+quiet)
			}
		}
	}
	b.WriteString(`"/></svg>`)
	return template.HTML(b.String()), nil //nolint:gosec // generated markup without user text
}
